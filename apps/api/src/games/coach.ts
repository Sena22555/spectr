export const COACH_NAMES: Record<CoachId, string> = { lingo: 'Лина', math: 'Матвей', physics: 'Фотон', code: 'Байт' };
/** голоса Piper: у Лины — женский, у остальных — мужской */
export const COACH_VOICE: Record<CoachId, string> = {
  lingo: process.env.COACH_VOICE_F ?? 'ru_RU-irina-medium',
  math: process.env.COACH_VOICE_M ?? 'ru_RU-dmitri-medium',
  physics: process.env.COACH_VOICE_M ?? 'ru_RU-dmitri-medium',
  code: process.env.COACH_VOICE_M ?? 'ru_RU-dmitri-medium',
};

export function coachLines(id: CoachId): Record<CoachEvent, string[]> {
  const out = {} as Record<CoachEvent, string[]>;
  for (const ev of Object.keys(COMMON) as CoachEvent[]) out[ev] = [...COMMON[ev], ...(EXTRA[id][ev] ?? [])];
  return out;
}

let all: Map<string, Set<string>> | null = null;
/** Все фразы комментатора по голосам — только их можно озвучивать без подписи. */
export function coachTexts() {
  if (all) return all;
  all = new Map();
  for (const id of Object.keys(COACH_NAMES) as CoachId[]) {
    const voice = COACH_VOICE[id];
    const set = all.get(voice) ?? new Set<string>();
    for (const list of Object.values(coachLines(id))) for (const t of list) set.add(t);
    all.set(voice, set);
  }
  return all;
}
