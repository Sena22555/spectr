export type GameId = 'math' | 'physics' | 'code';

export type OrderKind = 'integers' | 'negatives' | 'fractions' | 'decimals' | 'percents' | 'powers' | 'length' | 'mass' | 'time' | 'speed' | 'binary' | 'bytes';

export interface Chapter {
  id: string;
  title: string;
  sub: string;
  icon: string;
  grades: [number, number];
  /** генераторы тренажёров, из которых собираются карточки */
  gens: string[];
  /** короткая шпаргалка — первая карточка «Разминки» */
  cheat: string[];
  /** пары для «Найди пару»: левое ↔ правое (правые значения не повторяются) */
  pairs: [string, string][];
  order: OrderKind;
}

export interface Game {
  id: GameId;
  name: string;
  subject: 'math' | 'physics' | 'informatics';
  tagline: string;
  hue: number;
  icon: string;
  chapters: Chapter[];
}

