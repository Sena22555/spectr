export const findGame = (id: string) => GAMES.find((g) => g.id === id) ?? null;
export const levelId = (chapter: string, n: number) => `${chapter}-${n}`;
export function findLevel(game: Game, id: string) {
  const m = /^([a-z]+)-([1-3])$/.exec(id);
  if (!m) return null;
  const chapter = game.chapters.find((c) => c.id === m[1]);
  const level = LEVELS.find((l) => l.n === Number(m[2]));
  return chapter && level ? { chapter, level } : null;
}
