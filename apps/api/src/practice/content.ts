// Практикум «Спектра»: бесплатные темы с короткой теорией, формулами и задачами с автопроверкой.
// Формулы и решения пишутся в TeX между $…$ (сайт рисует их KaTeX), у формулы есть plain-версия для ботов.
// Условия задач — обычным текстом с юникодом, чтобы их можно было показать и в мессенджере.

export type Block = { kind: 'p' | 'tip' | 'warn'; text: string };

export interface Formula {
  tex: string;
  plain: string;
  label: string;
}

export interface Problem {
  id: string;
  text: string;
  /** number — число (допуск tol), text — строка из списка, choice — индекс варианта */
  kind: 'number' | 'text' | 'choice';
  answer: number | string[];
  tol?: number;
  unit?: string;
  options?: string[];
  hint: string;
  solution: string[];
  level: 1 | 2 | 3;
  /** задача «для самостоятельного решения»: без подсказки в первой попытке */
  self?: boolean;
}

export interface Topic {
  slug: string;
  title: string;
  level: string;
  minutes: number;
  summary: string;
  widget?: 'refraction' | 'binary' | 'motion' | 'ohm' | 'quadratic' | 'percent';
  theory: Block[];
  formulas: Formula[];
  example: { text: string; steps: string[] };
  problems: Problem[];
}

export interface PracticeSubject {
  slug: string;
  title: string;
  hue: number;
  emoji: string;
  blurb: string;
  /** slug предмета школы — для кнопки «Разобрать с репетитором» */
  course: string;
  topics: Topic[];
}

