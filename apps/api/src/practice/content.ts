export const ALL_TOPICS = PRACTICE.flatMap((s) => s.topics.map((t) => ({ subject: s, topic: t })));
export const ALL_PROBLEMS = ALL_TOPICS.flatMap(({ subject, topic }) => topic.problems.map((p) => ({ subject, topic, problem: p })));
const BY_ID = new Map(ALL_PROBLEMS.map((x) => [x.problem.id, x]));

export const findProblem = (id: string) => BY_ID.get(id);
export const findTopic = (subject: string, slug: string) => ALL_TOPICS.find((x) => x.subject.slug === subject && x.topic.slug === slug);

function parseNumber(raw: string) {
  const s = raw
    .trim()
    .replace(/\s+/g, '')
    .replace(',', '.')
    .replace(/[^0-9.\-+eE/]/g, '');
  if (/^-?\d+\/\d+$/.test(s)) {
    const [a, b] = s.split('/').map(Number);
    return b ? a! / b! : NaN;
  }
  return s === '' ? NaN : Number(s);
}

/** Проверка ответа. Для choice ответ — индекс варианта строкой. */
export function checkAnswer(p: Problem, raw: string) {
  if (p.kind === 'choice') return Number(raw) === p.answer;
  if (p.kind === 'text') {
    const norm = raw.trim().toLowerCase().replace(/\s+/g, '').replace(/ё/g, 'е');
    return (p.answer as string[]).some((a) => a.toLowerCase().replace(/\s+/g, '') === norm);
  }
  const value = parseNumber(raw);
  if (!Number.isFinite(value)) return false;
  return Math.abs(value - (p.answer as number)) <= (p.tol ?? 1e-6);
}

/** Правильный ответ строкой — для показа после попытки. */
export function answerText(p: Problem) {
  if (p.kind === 'choice') return p.options![p.answer as number]!;
  if (p.kind === 'text') return (p.answer as string[])[0]!;
  return `${String(p.answer).replace('.', ',')}${p.unit ? ` ${p.unit}` : ''}`;
}

/** Задача без ответа и решения — то, что можно отдать браузеру до попытки. */
export function publicProblem(p: Problem) {
  return { id: p.id, text: p.text, kind: p.kind, unit: p.unit ?? null, options: p.options ?? null, level: p.level, self: Boolean(p.self), hint: p.hint };
}

const SUP: Record<string, string> = { '0': '⁰', '1': '¹', '2': '²', '3': '³', '4': '⁴', '5': '⁵', '6': '⁶', '7': '⁷', '8': '⁸', '9': '⁹', '-': '⁻', n: 'ⁿ', '+': '⁺' };

const wrap = (x: string) => (/[\s+\-−·]/.test(x.trim()) ? `(${x.trim()})` : x.trim());

/** TeX → читаемый текст для мессенджеров (простые случаи). */
export function texToPlain(s: string) {
  return s
    .replace(/\$([^$]+)\$/g, (_, tex: string) =>
      tex
        .replace(/\\[dt]?frac\{([^{}]+)\}\{([^{}]+)\}/g, (_m, a: string, b: string) => `${wrap(a)}/${wrap(b)}`)
        .replace(/\\sqrt\{([^{}]+)\}/g, '√($1)')
        .replace(/\^\{([^{}]+)\}|\^(\d)/g, (_m, a: string | undefined, b: string | undefined) => [...(a ?? b ?? '')].map((ch) => SUP[ch] ?? ch).join(''))
        .replace(/\\cdot/g, '·')
        .replace(/\\pm/g, '±')
        .replace(/\\circ/g, '°')
        .replace(/\\(sin|cos|arcsin)/g, '$1')
        .replace(/\\operatorname\{tg\}/g, 'tg')
        .replace(/\\(alpha|beta)/g, (_m, g: string) => (g === 'alpha' ? 'α' : 'β'))
        .replace(/\\text\{([^{}]*)\}/g, '$1')
        .replace(/\{,\}/g, ',')
        .replace(/\\[,;: ]/g, ' ')
        .replace(/\\quad/g, '  ')
        .replace(/[{}]/g, '')
        .replace(/\\/g, ''),
    )
    .replace(/`/g, '');
}

/** «Задача дня»: одна и та же для всех в этот день, перебирает все задачи с числовым ответом или вариантами. */
export function dailyProblem(day: string) {
  const pool = ALL_PROBLEMS.filter((x) => x.problem.kind !== 'text');
  let h = 0;
  for (const ch of day) h = (h * 31 + ch.charCodeAt(0)) >>> 0;
  return pool[h % pool.length]!;
}
