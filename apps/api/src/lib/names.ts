// Имена в публичных таблицах (турнир, вызовы): их видят дети, поэтому чистим и не пускаем грубые слова.
// \b в JS не видит границ кириллических слов, поэтому границы — через \p{L}
const BAD = /(хуй|хуе|хуё|хуя|пизд|ебан|ебат|ебал|ебуч|ёб|бля[дт]|(?<!\p{L})бля(?!\p{L})|(?<!\p{L})сук[аиу](?!\p{L})|мудак|мудил|говн|залуп|шлюх|дрочи|пидор|пидар)/iu;

export const cleanName = (raw: string) =>
  raw
    .replace(/[^\p{L}\p{N} .\-_]/gu, '')
    .replace(/\s+/g, ' ')
    .trim()
    .slice(0, 24);

export const isRude = (name: string) => BAD.test(name);
